package frankenphp

import (
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"

	"flock/internal/supervisor"
)

// Site is a site to serve with FrankenPHP.
type Site struct {
	Name    string
	Path    string // the project
	Root    string // its document root
	Minor   string // the PHP version
	Port    int    // loopback port the web server proxies to
	Secured bool   // served over HTTPS: PHP sees HTTPS=on (the web server redirects plain HTTP)
	Octane  bool   // worker mode through Laravel Octane
	Env     []string
	// Restart is bumped to restart the process (e.g. to load changed code into Octane's workers).
	Restart int
}

// ProcessName is the supervised process (and log) of a site: "frankenphp-<site>".
func ProcessName(site string) string { return "frankenphp-" + site }

// siteDir holds a site's generated Caddyfile and Caddy's storage.
func siteDir(root, site string) string { return filepath.Join(root, "frankenphp", "sites", site) }

// OctaneWorker is the script Octane's worker mode runs, from Laravel Octane's package.
func OctaneWorker(path string) string {
	return filepath.Join(path, "vendor", "laravel", "octane", "bin", "frankenphp-worker.php")
}

// HasOctane reports whether a project has Laravel Octane installed.
func HasOctane(path string) bool { return fileExists(OctaneWorker(path)) }

// workerFile is public/frankenphp-worker.php, the entry point `php artisan octane:frankenphp`
// creates too (Octane's installer adds it to .gitignore).
const workerFile = "frankenphp-worker.php"

//go:embed frankenphp-worker.php.stub
var workerStub []byte

// ensureWorkerFile creates the document root's frankenphp-worker.php from Octane's stub, as
// `php artisan octane:frankenphp` does.
func ensureWorkerFile(s Site) error {
	if !HasOctane(s.Path) {
		return errors.New("Laravel Octane isn't installed — run `composer require laravel/octane`, or switch the site to classic mode")
	}
	target := filepath.Join(s.Root, workerFile)
	if fileExists(target) {
		return nil
	}
	stub, err := os.ReadFile(filepath.Join(s.Path, "vendor", "laravel", "octane", "src", "Commands", "stubs", workerFile))
	if err != nil {
		stub = workerStub
	}
	return os.WriteFile(target, stub, 0o644)
}

// Caddyfile is a site's server config: plain HTTP on the loopback port, the app's document root,
// and in Octane mode the worker. Exported for tests.
func Caddyfile(root string, s Site) string {
	var b strings.Builder
	dir := siteDir(root, s.Name)
	fmt.Fprintf(&b, `# Generated by Flock on every start.
{
	admin off
	persist_config off
	auto_https off
	skip_install_trust
	storage file_system %s
`, quote(filepath.Join(dir, "data")))
	if s.Octane {
		fmt.Fprintf(&b, "\tfrankenphp {\n\t\tworker {\n\t\t\tfile %s\n\t\t}\n\t}\n", quote(filepath.Join(s.Root, workerFile)))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "http://:%d {\n\tbind 127.0.0.1\n\troot * %s\n\tphp_server {\n", s.Port, quote(s.Root))
	if s.Secured {
		b.WriteString("\t\tenv HTTPS on\n")
	}
	if s.Octane {
		fmt.Fprintf(&b, "\t\tindex %[1]s\n\t\ttry_files {path} %[1]s\n\t\tresolve_root_symlink\n", workerFile)
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}

// Spec writes a site's Caddyfile and returns its process. The FrankenPHP build for s.Minor must be
// installed.
func Spec(root string, s Site) (supervisor.Spec, error) {
	binary := Binary(root, s.Minor)
	if binary == "" {
		return supervisor.Spec{}, fmt.Errorf("FrankenPHP for PHP %s is not installed", s.Minor)
	}
	if s.Octane {
		if err := ensureWorkerFile(s); err != nil {
			return supervisor.Spec{}, err
		}
	}
	if err := EnsureIni(root, s.Minor); err != nil {
		return supervisor.Spec{}, err
	}

	dir := siteDir(root, s.Name)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return supervisor.Spec{}, err
	}
	conf := Caddyfile(root, s)
	file := filepath.Join(dir, "Caddyfile")
	if err := os.WriteFile(file, []byte(conf), 0o600); err != nil {
		return supervisor.Spec{}, err
	}

	info, _ := InstalledInfo(root, s.Minor)
	sum := sha256.Sum256([]byte(conf))
	env := append(Env(root, s.Minor),
		// These change the spec when the config, the build or the restart counter change, so the
		// supervisor restarts the process.
		"FLOCK_CONFIG="+hex.EncodeToString(sum[:8]),
		fmt.Sprintf("FLOCK_FRANKENPHP=%s+%d", info.Version, info.Build),
		"FLOCK_RESTART="+strconv.Itoa(s.Restart),
	)
	if s.Octane {
		env = append(env, "APP_BASE_PATH="+s.Path, "APP_PUBLIC_PATH="+s.Root, "LARAVEL_OCTANE=1", "MAX_REQUESTS=500")
	}
	env = append(env, s.Env...)

	return supervisor.Spec{
		Name:       ProcessName(s.Name),
		Path:       binary,
		Args:       []string{"run", "--config", file, "--adapter", "caddyfile"},
		Env:        env,
		Dir:        s.Path,
		LogFile:    filepath.Join(root, "log", ProcessName(s.Name)+".log"),
		StopSignal: syscall.SIGTERM, // graceful: finish in-flight requests
	}, nil
}

// quote makes a Caddyfile token; Windows paths get forward slashes (see web.quote).
func quote(s string) string {
	if strings.HasPrefix(s, `\\`) || (len(s) > 2 && s[1] == ':' && (s[2] == '\\' || s[2] == '/')) {
		s = strings.ReplaceAll(s, `\`, "/")
	}
	return strconv.Quote(s)
}
